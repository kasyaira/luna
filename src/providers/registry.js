export const PROVIDER_BY_ID = Object.fromEntries(PROVIDERS.map((p) => [p.id, p]));

/** Ordering when provider=auto: user keys first (best quality), then keyless, then local. */
export function autoOrder(keys = {}, cfg = {}) {
  const scored = PROVIDERS.map((p) => {
    let score = 1000 + (p.rank ?? 50);
    const hasKey = p.kind === 'keyed' && (keys[p.id] || (p.id === 'custom' && cfg.apiKey));
    if (p.id === 'custom' && cfg.baseUrl) score = 1;           // explicit custom setup wins
    else if (hasKey) score = 100 + (p.rank ?? 50);              // keyed providers next
    else if (p.kind === 'keyless') score = 300;                 // pollinations always available
    else score = 400;                                           // local, only if detected
    return { p, score };
  });
  scored.sort((a, b) => a.score - b.score || (a.p.rank ?? 0) - (b.p.rank ?? 0));
  return scored.map((s) => s.p.id);
}
